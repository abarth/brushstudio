/** Characters with no glyph of their own that read fine as something else. */
const SUBSTITUTES: Record<string, string> = {
  '—': '-',
  '–': '-',
  '‘': "'",
  '’': "'",
  '“': '"',
  '”': '"',
  '…': '...',
  '≥': '>=',
  '≤': '<=',
  '±': '+/-',
};

const GLYPH_W = 5;
const GLYPH_H = 8;
const TRACKING = 1; // blank column between glyphs

export interface TextStyle {
  /** integer pixel multiplier; 2 is the readable minimum on a plate */
  scale?: number;
  /** straight (un-premultiplied) 0..1 colour */
  color?: [number, number, number];
  /** 0..1 */
  alpha?: number;
  /** draw the glyphs one pixel thicker, for headings */
  bold?: boolean;
}

function normalise(text: string): string {
  let out = '';
  for (const ch of text) {
    if (GLYPHS[ch]) out += ch;
    else if (SUBSTITUTES[ch]) out += SUBSTITUTES[ch];
    else out += ch.codePointAt(0)! < 32 ? ' ' : '?';
  }
  return out;
}

export function textWidth(text: string, scale = 2, bold = false): number {
  const chars = normalise(text).length;
  return chars * (GLYPH_W + TRACKING) * scale + (bold ? scale : 0);
}

export const textHeight = (scale = 2): number => GLYPH_H * scale;

/**
 * Draws text into a premultiplied RGBA8 buffer, `x`/`y` being the top-left
 * of the first glyph. Alpha-blends, so captions can sit over the marks.
 */
export function drawText(
  buf: Uint8Array,
  bufWidth: number,
  bufHeight: number,
  text: string,
  x: number,
  y: number,
  style: TextStyle = {},
): void {
  const scale = Math.max(1, Math.round(style.scale ?? 2));
  const [r, g, b] = style.color ?? [0, 0, 0];
  const alpha = style.alpha ?? 1;
  if (alpha <= 0) return;
  const bold = !!style.bold;

  let penX = x;
  for (const ch of normalise(text)) {
    const glyph = GLYPHS[ch] ?? GLYPHS['?'];
    for (let col = 0; col < GLYPH_W; col++) {
      const bits = glyph[col];
      for (let row = 0; row < GLYPH_H; row++) {
        if ((bits & (1 << row)) === 0) continue;
        // one source pixel becomes a scale x scale block, plus an extra
        // column to the right when bold
        const px0 = penX + col * scale;
        const py0 = y + row * scale;
        const w = scale + (bold ? 1 : 0);
        for (let dy = 0; dy < scale; dy++) {
          const py = py0 + dy;
          if (py < 0 || py >= bufHeight) continue;
          for (let dx = 0; dx < w; dx++) {
            const px = px0 + dx;
            if (px < 0 || px >= bufWidth) continue;
            const idx = (py * bufWidth + px) * 4;
            const inv = 1 - alpha;
            buf[idx] = Math.round(Math.min(255, r * alpha * 255 + buf[idx] * inv));
            buf[idx + 1] = Math.round(Math.min(255, g * alpha * 255 + buf[idx + 1] * inv));
            buf[idx + 2] = Math.round(Math.min(255, b * alpha * 255 + buf[idx + 2] * inv));
            buf[idx + 3] = Math.round(Math.min(255, alpha * 255 + buf[idx + 3] * inv));
          }
        }
      }
    }
    penX += (GLYPH_W + TRACKING) * scale;
  }
}

/** Fills a rectangle with a straight colour (used for rules and grounds). */
export function fillRect(
  buf: Uint8Array,
  bufWidth: number,
  bufHeight: number,
  x: number,
  y: number,
  w: number,
  h: number,
  color: [number, number, number, number],
): void {
  const a = color[3];
  const bytes = [
    Math.round(color[0] * a * 255),
    Math.round(color[1] * a * 255),
    Math.round(color[2] * a * 255),
    Math.round(a * 255),
  ];
  const x1 = Math.min(bufWidth, x + w);
  const y1 = Math.min(bufHeight, y + h);
  for (let py = Math.max(0, y); py < y1; py++) {
    for (let px = Math.max(0, x); px < x1; px++) {
      const idx = (py * bufWidth + px) * 4;
      buf[idx] = bytes[0];
      buf[idx + 1] = bytes[1];
      buf[idx + 2] = bytes[2];
      buf[idx + 3] = bytes[3];
    }
  }
}

/** Every glyph in the table, for eyeballing the font itself. */
export const GLYPH_CHARS = Object.keys(GLYPHS);

/**
 * Breaks a caption to fit a width, preferring the ` · ` separators the
 * settings summary already uses and falling back to a hard split.
 */
export function wrapText(text: string, maxWidth: number, scale = 2, bold = false): string[] {
  if (textWidth(text, scale, bold) <= maxWidth) return [text];
  const perChar = textWidth('m', scale, bold);
  const limit = Math.max(8, Math.floor(maxWidth / perChar));
  const lines: string[] = [];
  let rest = text;
  while (rest.length > limit) {
    const window = rest.slice(0, limit);
    const at = window.lastIndexOf(' · ');
    const cut = at > limit * 0.4 ? at + 2 : window.lastIndexOf(' ');
    const take = cut > limit * 0.4 ? cut : limit;
    lines.push(rest.slice(0, take).trimEnd());
    rest = rest.slice(take).trimStart();
  }
  if (rest) lines.push(rest);
  return lines;
}
